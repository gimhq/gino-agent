#!/usr/bin/env bun
/* eslint-disable no-console */
/**
 * Generates the e2ee field-map tables (docs/e2ee/spec.md §12.6).
 *
 * Reads every `docs/e2ee/*.fieldmap.json`, validates it against spec
 * §12.1–§12.3 and §12.5, and writes:
 *   - gino-e2ee/src/field_map/generated.rs
 *   - sdks/e2ee/src/field-map.generated.ts
 *
 * Usage:  bun run gen:field-map            (write the outputs)
 *         bun run gen:field-map --check    (exit 1 if a committed output differs)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import process from "node:process";

const ROOT = resolve(import.meta.dir, "../../..");
const SOURCE_DIR = join(ROOT, "docs", "e2ee");
const RUST_OUT = join(ROOT, "gino-e2ee", "src", "field_map", "generated.rs");
const TS_OUT = join(ROOT, "sdks", "e2ee", "src", "field-map.generated.ts");
const FORMAT = "gino-e2ee/field-map/v1";
const HEADER = "Generated by sdks/e2ee/scripts/gen-field-map.ts from docs/e2ee/*.fieldmap.json. Do not edit.";

type Direction = "host_to_agent" | "agent_to_host";
type Kind = "text" | "json" | "blob";
type Envelope = "content" | "drop" | "file";

interface When { path: string; op: "eq" | "ne"; value: string }
interface KeyedPlain { key: string; table: [string, string[]][] }
interface FieldRule {
  path: string;
  kind: Kind;
  envelopes: Envelope[];
  aad: string;
  when?: When;
  keyedPlain?: KeyedPlain;
}
interface FrameRule { frameType: string; direction: Direction; scope: string; fields: FieldRule[] }
interface FieldMap { name: string; file: string; profile: string; frames: FrameRule[] }

class MapError extends Error {}

function fail(where: string, message: string): never {
  throw new MapError(`${where}: ${message}`);
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function onlyKeys(where: string, value: Record<string, unknown>, required: string[], optional: string[] = []): void {
  for (const key of required) {
    if (!(key in value))
      fail(where, `missing \`${key}\``);
  }
  for (const key of Object.keys(value)) {
    if (!required.includes(key) && !optional.includes(key))
      fail(where, `unknown member \`${key}\``);
  }
}

function str(where: string, value: unknown): string {
  if (typeof value !== "string" || value === "")
    fail(where, "expected a non-empty string");
  return value;
}

// ---------------------------------------------------------------------------
// Paths (§12.2): dot-separated keys `[A-Za-z0-9_]+`, a segment may end in `[]`.

interface Step { member?: string; element?: true }

const KEY = /^\w+$/;

function frameSteps(where: string, path: string, allowArrays: boolean): Step[] {
  const steps: Step[] = [];
  for (const segment of path.split(".")) {
    const isArray = segment.endsWith("[]");
    const key = isArray ? segment.slice(0, -2) : segment;
    if (!KEY.test(key))
      fail(where, `invalid path \`${path}\``);
    if (isArray && !allowArrays)
      fail(where, `\`[]\` is not allowed in \`${path}\``);
    steps.push({ member: key });
    if (isArray)
      steps.push({ element: true });
  }
  return steps;
}

function sameStep(a: Step, b: Step): boolean {
  return a.element === b.element && a.member === b.member;
}

/** Whether `prefix` is a (non-strict) step prefix of `path`. */
function isPrefix(prefix: Step[], path: Step[]): boolean {
  return prefix.length <= path.length && prefix.every((step, i) => sameStep(step, path[i]!));
}

// ---------------------------------------------------------------------------
// Validation.

function parseWhen(where: string, value: unknown): When {
  if (!isObject(value))
    fail(where, "`when` must be an object");
  onlyKeys(`${where}.when`, value, ["path", "op", "value"]);
  const path = str(`${where}.when.path`, value.path);
  frameSteps(`${where}.when`, path, false);
  if (value.op !== "eq" && value.op !== "ne")
    fail(`${where}.when`, "`op` must be `eq` or `ne`");
  if (typeof value.value !== "string")
    fail(`${where}.when`, "`value` must be a string");
  return { path, op: value.op, value: value.value };
}

/** Validates a plain path list (§12.5) and returns it. */
function parsePlainList(where: string, value: unknown): string[] {
  if (!Array.isArray(value))
    fail(where, "expected an array of plain paths");
  const lists: Step[][] = [];
  const seen = new Set<string>();
  for (const item of value) {
    const path = str(where, item);
    if (seen.has(path))
      fail(where, `duplicate plain path \`${path}\``);
    seen.add(path);
    const steps = frameSteps(where, path, true);
    if (steps.some(step => step.member === "e2ee"))
      fail(where, `\`e2ee\` is not a plain name (\`${path}\`)`);
    lists.push(steps);
  }
  for (const [i, a] of lists.entries()) {
    for (const [j, b] of lists.entries()) {
      if (i === j)
        continue;
      if (isPrefix(a, b))
        fail(where, `plain path \`${value[i]}\` is a prefix of \`${value[j]}\``);
      const shared = a.findIndex((step, k) => k >= b.length || !sameStep(step, b[k]!));
      if (shared >= 0 && shared < b.length && Boolean(a[shared]!.element) !== Boolean(b[shared]!.element))
        fail(where, `plain paths \`${value[i]}\` and \`${value[j]}\` step into the same position as object and array`);
    }
  }
  return value as string[];
}

function parseKeyedPlain(where: string, value: unknown): KeyedPlain {
  if (!isObject(value))
    fail(where, "`keyed_plain` must be an object");
  onlyKeys(`${where}.keyed_plain`, value, ["key", "table"]);
  const key = str(`${where}.keyed_plain.key`, value.key);
  frameSteps(`${where}.keyed_plain`, key, false);
  if (!isObject(value.table))
    fail(`${where}.keyed_plain`, "`table` must be an object");
  const table: [string, string[]][] = Object.entries(value.table).map(([method, list]) => [
    method,
    parsePlainList(`${where}.keyed_plain.table.${method}`, list),
  ]);
  return { key, table };
}

interface Template { parts: { name: string; value: string; placeholder?: string }[] }

function parseTemplate(where: string, aad: string): Template {
  const parts = aad.split("|").map((part) => {
    const colon = part.indexOf(":");
    if (colon < 0)
      fail(where, `AAD part \`${part}\` has no \`:\``);
    const name = part.slice(0, colon);
    const value = part.slice(colon + 1);
    if (!/^[a-z0-9_]+$/.test(name))
      fail(where, `invalid AAD name \`${name}\``);
    if (value === "")
      fail(where, `empty AAD value for \`${name}\``);
    const placeholder = value.startsWith("{") && value.endsWith("}") ? value.slice(1, -1) : undefined;
    if (placeholder === undefined && /[{}]/.test(value))
      fail(where, `a placeholder must be a whole value (\`${value}\`)`);
    return placeholder === undefined ? { name, value } : { name, value, placeholder };
  });
  return { parts };
}

function parseRule(where: string, value: unknown, scope: string): FieldRule {
  if (!isObject(value))
    fail(where, "a field rule must be an object");
  onlyKeys(where, value, ["path", "kind", "envelopes", "aad"], ["when", "keyed_plain"]);
  const path = str(`${where}.path`, value.path);
  const steps = frameSteps(where, path, true);
  const kind = value.kind;
  if (kind !== "text" && kind !== "json" && kind !== "blob")
    fail(where, "`kind` must be `text`, `json` or `blob`");
  if (!Array.isArray(value.envelopes) || value.envelopes.length === 0)
    fail(where, "`envelopes` must be a non-empty array");
  const envelopes = value.envelopes as Envelope[];
  if (new Set(envelopes).size !== envelopes.length)
    fail(where, "duplicate envelope type");
  if (kind === "blob") {
    if (envelopes.length !== 1 || envelopes[0] !== "file")
      fail(where, "a `blob` rule allows exactly `[\"file\"]`");
  }
  else if (!envelopes.includes("content") || envelopes.some(e => e !== "content" && e !== "drop")) {
    fail(where, "a `text`/`json` rule allows `content` and optionally `drop`");
  }

  const aad = str(`${where}.aad`, value.aad);
  const template = parseTemplate(where, aad);
  const [first] = template.parts;
  if (first?.name !== "scope" || first.placeholder !== scope)
    fail(where, `the AAD template must start with \`scope:{${scope}}\``);
  for (const part of template.parts) {
    if (part.placeholder === undefined)
      continue;
    const placeholder = frameSteps(where, part.placeholder, true);
    const lastElement = placeholder.findLastIndex(step => step.element);
    if (lastElement >= 0 && !isPrefix(placeholder.slice(0, lastElement + 1), steps))
      fail(where, `placeholder \`{${part.placeholder}}\` must share the rule path up to its \`[]\``);
  }

  const rule: FieldRule = { path, kind, envelopes, aad };
  if (value.when !== undefined)
    rule.when = parseWhen(where, value.when);
  if (value.keyed_plain !== undefined) {
    if (kind !== "json")
      fail(where, "`keyed_plain` is only allowed on `json` rules");
    if (template.parts.at(-1)?.placeholder !== undefined)
      fail(where, "the last AAD part of a `keyed_plain` rule must be literal");
    rule.keyedPlain = parseKeyedPlain(where, value.keyed_plain);
  }
  return rule;
}

/** Two rules can apply to the same frame unless their `when`s are `eq`/`ne` on one path and value. */
function canCoApply(a: FieldRule, b: FieldRule): boolean {
  if (!a.when || !b.when)
    return true;
  return !(a.when.path === b.when.path && a.when.value === b.when.value && a.when.op !== b.when.op);
}

/** Rule-set checks of §12.2, §12.3 and §12.5 over one frame. */
function checkFrame(where: string, frame: FrameRule): void {
  const sealing = frame.fields.filter(rule => rule.kind !== "blob");
  const cleartext = (label: string, path: string, rule: FieldRule): void => {
    const steps = frameSteps(where, path, true);
    for (const other of sealing) {
      if (canCoApply(rule, other) && isPrefix(frameSteps(where, other.path, true), steps))
        fail(where, `${label} \`${path}\` is at or below the sealed path \`${other.path}\``);
    }
  };
  for (const [i, a] of sealing.entries()) {
    for (const b of sealing.slice(i + 1)) {
      const [sa, sb] = [frameSteps(where, a.path, true), frameSteps(where, b.path, true)];
      if (canCoApply(a, b) && (isPrefix(sa, sb) || isPrefix(sb, sa)))
        fail(where, `rules \`${a.path}\` and \`${b.path}\` overlap`);
    }
  }
  for (const rule of frame.fields) {
    cleartext("the scope path", frame.scope, rule);
    for (const part of parseTemplate(where, rule.aad).parts) {
      if (part.placeholder !== undefined)
        cleartext("placeholder", part.placeholder, rule);
    }
    if (rule.when)
      cleartext("the `when` path", rule.when.path, rule);
    if (rule.keyedPlain)
      cleartext("the discriminator", rule.keyedPlain.key, rule);
  }
}

function parseMap(file: string, text: string): FieldMap {
  let json: unknown;
  try {
    json = JSON.parse(text);
  }
  catch (error) {
    fail(file, `invalid JSON: ${(error as Error).message}`);
  }
  if (!isObject(json))
    fail(file, "a field map must be an object");
  onlyKeys(file, json, ["format", "profile", "frames"]);
  if (json.format !== FORMAT)
    fail(file, `\`format\` must be \`${FORMAT}\``);
  const profile = str(`${file}.profile`, json.profile);
  if (!isObject(json.frames))
    fail(file, "`frames` must be an object");
  const frames = Object.entries(json.frames).map(([frameType, value]): FrameRule => {
    const where = `${file}.frames.${frameType}`;
    if (frameType === "")
      fail(where, "empty frame type");
    if (!isObject(value))
      fail(where, "a frame must be an object");
    onlyKeys(where, value, ["direction", "scope", "fields"]);
    if (value.direction !== "host_to_agent" && value.direction !== "agent_to_host")
      fail(where, "`direction` must be `host_to_agent` or `agent_to_host`");
    const scope = str(`${where}.scope`, value.scope);
    frameSteps(where, scope, false);
    if (!Array.isArray(value.fields))
      fail(where, "`fields` must be an array");
    const fields = value.fields.map((rule, i) => parseRule(`${where}.fields[${i}]`, rule, scope));
    const frame: FrameRule = { frameType, direction: value.direction as Direction, scope, fields };
    checkFrame(where, frame);
    return frame;
  });
  const name = file.replace(/\.fieldmap\.json$/, "");
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name))
    fail(file, "the file name must be `<lower-kebab-name>.fieldmap.json`");
  return { name, file, profile, frames };
}

// ---------------------------------------------------------------------------
// Output.

const ENVELOPE_RS: Record<Envelope, string> = { content: "Content", drop: "Drop", file: "File" };
const KIND_RS: Record<Kind, string> = { text: "Text", json: "Json", blob: "Blob" };
const DIRECTION_RS: Record<Direction, string> = { host_to_agent: "HostToAgent", agent_to_host: "AgentToHost" };

function constName(map: FieldMap): string {
  return map.name.toUpperCase().replaceAll("-", "_");
}

function camelName(map: FieldMap): string {
  return map.name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function rsStr(value: string): string {
  const escaped = [...value].map((c) => {
    if (c === "\\" || c === "\"")
      return `\\${c}`;
    const code = c.codePointAt(0) ?? 0;
    return code < 0x20 || code === 0x7F ? `\\u{${code.toString(16)}}` : c;
  });
  return `"${escaped.join("")}"`;
}

function rsRule(rule: FieldRule, pad: string): string {
  const lines = [
    `${pad}FieldRule {`,
    `${pad}    path: ${rsStr(rule.path)},`,
    `${pad}    kind: Kind::${KIND_RS[rule.kind]},`,
    `${pad}    envelopes: &[${rule.envelopes.map(e => `EnvelopeType::${ENVELOPE_RS[e]}`).join(", ")}],`,
    `${pad}    aad: ${rsStr(rule.aad)},`,
  ];
  if (rule.when) {
    const op = rule.when.op === "eq" ? "Eq" : "Ne";
    lines.push(`${pad}    when: Some(When { path: ${rsStr(rule.when.path)}, op: WhenOp::${op}, value: ${rsStr(rule.when.value)} }),`);
  }
  else {
    lines.push(`${pad}    when: None,`);
  }
  if (rule.keyedPlain) {
    lines.push(`${pad}    keyed_plain: Some(KeyedPlain {`, `${pad}        key: ${rsStr(rule.keyedPlain.key)},`);
    if (rule.keyedPlain.table.length === 0) {
      lines.push(`${pad}        table: &[],`);
    }
    else {
      lines.push(`${pad}        table: &[`);
      for (const [method, paths] of rule.keyedPlain.table)
        lines.push(`${pad}            (${rsStr(method)}, &[${paths.map(rsStr).join(", ")}]),`);
      lines.push(`${pad}        ],`);
    }
    lines.push(`${pad}    }),`);
  }
  else {
    lines.push(`${pad}    keyed_plain: None,`);
  }
  lines.push(`${pad}},`);
  return lines.join("\n");
}

function renderRust(maps: FieldMap[]): string {
  const out = [
    `//! ${HEADER}`,
    "",
    "use super::{Direction, FieldMap, FieldRule, FrameRule, KeyedPlain, Kind, When, WhenOp};",
    "use crate::EnvelopeType;",
    "",
    "/// The field map of every profile.",
    `pub const PROFILES: &[&FieldMap] = &[${maps.map(m => `&${constName(m)}`).join(", ")}];`,
  ];
  for (const map of maps) {
    out.push(
      "",
      `/// \`${map.profile}\`, from \`docs/e2ee/${map.file}\`.`,
      `pub const ${constName(map)}: FieldMap = FieldMap {`,
      `    profile: ${rsStr(map.profile)},`,
      "    frames: &[",
    );
    for (const frame of map.frames) {
      out.push(
        "        FrameRule {",
        `            frame_type: ${rsStr(frame.frameType)},`,
        `            direction: Direction::${DIRECTION_RS[frame.direction]},`,
        `            scope: ${rsStr(frame.scope)},`,
        "            fields: &[",
        ...frame.fields.map(rule => rsRule(rule, "                ")),
        "            ],",
        "        },",
      );
    }
    out.push("    ],", "};");
  }
  return `${out.join("\n")}\n`;
}

function tsStr(value: string): string {
  return JSON.stringify(value);
}

function tsRule(rule: FieldRule, pad: string): string {
  const lines = [
    `${pad}{`,
    `${pad}  path: ${tsStr(rule.path)},`,
    `${pad}  kind: ${tsStr(rule.kind)},`,
    `${pad}  envelopes: [${rule.envelopes.map(tsStr).join(", ")}],`,
    `${pad}  aad: ${tsStr(rule.aad)},`,
  ];
  if (rule.when)
    lines.push(`${pad}  when: { path: ${tsStr(rule.when.path)}, op: ${tsStr(rule.when.op)}, value: ${tsStr(rule.when.value)} },`);
  if (rule.keyedPlain) {
    const table = rule.keyedPlain.table;
    lines.push(`${pad}  keyedPlain: {`, `${pad}    key: ${tsStr(rule.keyedPlain.key)},`);
    if (table.length === 0) {
      lines.push(`${pad}    table: {},`);
    }
    else {
      lines.push(`${pad}    table: {`);
      for (const [method, paths] of table)
        lines.push(`${pad}      ${tsStr(method)}: [${paths.map(tsStr).join(", ")}],`);
      lines.push(`${pad}    },`);
    }
    lines.push(`${pad}  },`);
  }
  lines.push(`${pad}},`);
  return lines.join("\n");
}

function renderTs(maps: FieldMap[]): string {
  const out = [
    `// ${HEADER}`,
    "",
    "export type FieldKind = \"text\" | \"json\" | \"blob\";",
    "export type FieldEnvelope = \"content\" | \"drop\" | \"file\";",
    "export type FrameDirection = \"host_to_agent\" | \"agent_to_host\";",
    "",
    "export interface FieldWhen {",
    "  readonly path: string;",
    "  readonly op: \"eq\" | \"ne\";",
    "  readonly value: string;",
    "}",
    "",
    "export interface FieldKeyedPlain {",
    "  readonly key: string;",
    "  readonly table: Readonly<Record<string, readonly string[]>>;",
    "}",
    "",
    "export interface FieldRule {",
    "  readonly path: string;",
    "  readonly kind: FieldKind;",
    "  readonly envelopes: readonly FieldEnvelope[];",
    "  readonly aad: string;",
    "  readonly when?: FieldWhen;",
    "  readonly keyedPlain?: FieldKeyedPlain;",
    "}",
    "",
    "export interface FrameRule {",
    "  readonly direction: FrameDirection;",
    "  readonly scope: string;",
    "  readonly fields: readonly FieldRule[];",
    "}",
    "",
    "export interface FieldMap {",
    "  readonly profile: string;",
    "  readonly frames: Readonly<Record<string, FrameRule>>;",
    "}",
  ];
  for (const map of maps) {
    out.push(
      "",
      `/** \`${map.profile}\`, from \`docs/e2ee/${map.file}\`. */`,
      `export const ${camelName(map)}FieldMap: FieldMap = {`,
      `  profile: ${tsStr(map.profile)},`,
      "  frames: {",
    );
    for (const frame of map.frames) {
      out.push(
        `    ${frame.frameType}: {`,
        `      direction: ${tsStr(frame.direction)},`,
        `      scope: ${tsStr(frame.scope)},`,
        "      fields: [",
        ...frame.fields.map(rule => tsRule(rule, "        ")),
        "      ],",
        "    },",
      );
    }
    out.push("  },", "};");
  }
  out.push(
    "",
    "/** The field map of every profile, by profile id. */",
    "export const fieldMaps: Readonly<Record<string, FieldMap>> = {",
    ...maps.map(m => `  ${tsStr(m.profile)}: ${camelName(m)}FieldMap,`),
    "};",
  );
  return `${out.join("\n")}\n`;
}

// ---------------------------------------------------------------------------

function main(): number {
  const check = process.argv.includes("--check");
  const files = readdirSync(SOURCE_DIR).filter(f => f.endsWith(".fieldmap.json")).sort();
  if (files.length === 0) {
    console.error(`no *.fieldmap.json in ${relative(ROOT, SOURCE_DIR)}`);
    return 1;
  }
  let maps: FieldMap[];
  try {
    maps = files.map(file => parseMap(file, readFileSync(join(SOURCE_DIR, file), "utf8")));
  }
  catch (error) {
    if (error instanceof MapError) {
      console.error(`invalid field map: ${error.message}`);
      return 1;
    }
    throw error;
  }
  const profiles = new Set<string>();
  for (const map of maps) {
    if (profiles.has(map.profile)) {
      console.error(`duplicate profile id ${map.profile}`);
      return 1;
    }
    profiles.add(map.profile);
  }

  let stale = 0;
  for (const [path, content] of [[RUST_OUT, renderRust(maps)], [TS_OUT, renderTs(maps)]] as const) {
    const name = relative(ROOT, path);
    if (check) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
        console.error(`${name} is stale; run \`bun run gen:field-map\``);
        stale++;
      }
    }
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${name}`);
    }
  }
  return stale === 0 ? 0 : 1;
}

process.exit(main());
