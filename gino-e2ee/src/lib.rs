//! End-to-end encryption core for gino.
//!
//! One MLS group (RFC 9420, OpenMLS) per scope provides authenticated
//! membership and key agreement. Durable content is encrypted under per-epoch
//! keys taken from the MLS exporter, and non-members write through HPKE drops
//! to a per-epoch drop key.
//!
//! This layer works on given epoch secrets (`k_e`, `d_e`) and implements the
//! envelope format of `docs/e2ee/spec.md`:
//!
//! - [`Location`]: AAD location strings and their templates (§6, §12.3);
//! - [`seal_content`]/[`open_content`], [`seal_file`]/[`open_file`]: salted
//!   AES-256-GCM envelopes under a per-envelope key (§4.3, §5.3, §5.4);
//! - [`DropKeyPair`], [`seal_drop`]/[`open_drop`]: HPKE drops (§4.4, §5.5);
//! - [`seal_epoch_link`]/[`open_epoch_link`], [`KeyHistory`],
//!   [`HistoryPolicy`] and the backward walk of [`History`] (§5.6, §5.7, §7);
//! - [`Error`]: the failure codes of §11;
//! - [`field_map`]: the generated field maps (§12) and the engine that seals
//!   and opens whole frames, [`FieldMap::seal_frame`]/[`FieldMap::open_frame`].
//!
//! The MLS layer (spec §2–§4, §7) on OpenMLS:
//!
//! - [`Identity`] and [`KeyPackageStore`]: Ed25519 BasicCredential identities
//!   and one-time and last-resort KeyPackages;
//! - [`ScopeGroup`]: one group per scope, its commit units for the DS
//!   ([`CommitUnit`]), the handshake log applied in `seq` order
//!   ([`LogEntry`]), and the epoch secrets over a [`KeyCache`];
//! - [`StateStore`]: opaque per-scope snapshots of the group state;
//! - [`GroupError`]: §11 failures plus local sequencing conditions.
//!
//! Randomness is injected: salts come from an [`OpenMlsRand`] (in production
//! the OpenMLS provider, `openmls_rust_crypto::RustCrypto`), HPKE uses the
//! provider's [`OpenMlsCrypto`].
//!
//! `docs/e2ee/test-vectors.json` (spec §13) is generated by the ignored test
//! `write_test_vectors` in `tests/vectors.rs`:
//!
//! ```text
//! cargo test --test vectors -- --ignored write_test_vectors
//! ```
//!
//! The same file's normal tests fail if the committed vectors differ from the
//! generator output or do not verify.
//!
//! [`OpenMlsRand`]: openmls_traits::random::OpenMlsRand
//! [`OpenMlsCrypto`]: openmls_traits::crypto::OpenMlsCrypto

